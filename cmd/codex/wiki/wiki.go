// Package wiki generates Gollum wiki pages from game-data/ (codex --wiki <dir>).
//
// The output directory is a working copy of the wiki's git repo. The generator owns
// every page whose first line is the generated marker, plus the media/ folder: it
// rewrites those on each run and deletes the ones whose source data is gone.
// Anything else in the repo — hand-written pages, Home, the sidebar once it exists —
// is never touched, so generated reference pages and community pages live side by
// side. Pages are named by id (stable links when a name changes); Gollum runs with
// --h1-title so the first H1 is the displayed title.
package wiki

import (
	"crypto/sha256"
	_ "embed"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"html"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Marker is the first line of every generated page.
const Marker = "<!-- generated by codex --wiki: edits to this page are overwritten -->"

// Options says where to read game data and art, and where the wiki lives.
type Options struct {
	DataDir  string // game-data
	ImageDir string // www/res/img
	OutDir   string // wiki repo working copy
	BasePath string // where Gollum is served (gollum --base-path), e.g. "/wiki"
}

// Result counts what a run did.
type Result struct {
	Pages   int
	Images  int
	Removed int
}

// Generate writes the generated pages into opt.OutDir.
func Generate(opt Options) (*Result, error) {
	if err := os.MkdirAll(opt.OutDir, 0o755); err != nil {
		return nil, err
	}
	g := &gen{opt: opt, written: map[string]bool{}, res: &Result{}}
	if err := g.load(); err != nil {
		return nil, err
	}
	g.index()

	// media/ is wholly generated — start it clean so removed art disappears.
	if err := os.RemoveAll(filepath.Join(opt.OutDir, "media")); err != nil {
		return nil, err
	}

	steps := []func() error{
		g.writeItems, g.writeMonsters, g.writeSpells, g.writeLocations,
		g.writeNPCs, g.writeQuests, g.writeEncounters, g.writeCharacters,
		g.writeRules, g.writeGuides, g.writeMap, g.writeHome, g.writeTheme,
	}
	for _, step := range steps {
		if err := step(); err != nil {
			return nil, err
		}
	}
	if err := g.removeStale(); err != nil {
		return nil, err
	}
	return g.res, nil
}

type gen struct {
	opt     Options
	res     *Result
	written map[string]bool // slash paths written this run

	items     map[string]*item
	monsters  map[string]*monster
	spells    map[string]*spell
	cities    map[string]*city
	envs      map[string]*environment
	npcs      map[string]*npc
	effects   []*effect
	feats     []*feat
	abilities []*ability

	pois       map[string]*poi
	encounters map[string]*encounter
	quests     map[string]*quest
	chars      *characters

	// reverse indexes
	droppedBy map[string][]string // item id → monster ids
	soldBy    map[string][]string // item id → npc ids
	inPacks   map[string][]string // item id → pack ids
	setPieces map[string][]string // set item id → piece ids
	scrollsOf map[string][]string // spell id → scroll item ids
	usedBy    map[string][]string // component item id → spell ids
	npcsAt    map[string][]string // home id → npc ids
	district  map[string]string   // district id → city id
	foundIn   map[string][]string // item id → place/quest links it's found in
	metIn     map[string][]string // monster id → place/quest links it's met in
	poisIn    map[string][]string // environment id → poi ids
	questsAt  map[string][]string // poi id → quest ids

	x         *extras             // scribing, teleport, spell slot/learning config
	rewardOf  map[string][]string // item id → quests it's a reward of
	neededFor map[string][]string // item id → what it's handed in for / used by
	giftOf    map[string][]string // item id → npcs who give it in dialogue
	questsBy  map[string][]string // npc id → quests they give
}

// ── loading ──────────────────────────────────────────────────────────────────

func loadDir[T any](dir string, recursive bool, keep func(*T) bool) ([]*T, error) {
	var out []*T
	err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if path != dir && !recursive {
				return filepath.SkipDir
			}
			return nil
		}
		if filepath.Ext(path) != ".json" {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		v := new(T)
		if err := json.Unmarshal(data, v); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		if fa, ok := any(v).(interface{ setFile(string) }); ok {
			fa.setFile(path)
		}
		if keep == nil || keep(v) {
			out = append(out, v)
		}
		return nil
	})
	return out, err
}

func (g *gen) load() error {
	d := g.opt.DataDir
	items, err := loadDir[item](filepath.Join(d, "items"), false, nil)
	if err != nil {
		return err
	}
	monsters, err := loadDir[monster](filepath.Join(d, "monsters"), false, nil) // skips monsters/wip
	if err != nil {
		return err
	}
	spells, err := loadDir[spell](filepath.Join(d, "magic", "spells"), false, nil)
	if err != nil {
		return err
	}
	cities, err := loadDir[city](filepath.Join(d, "locations", "cities"), false, nil)
	if err != nil {
		return err
	}
	envs, err := loadDir[environment](filepath.Join(d, "locations", "environments"), false, nil)
	if err != nil {
		return err
	}
	npcs, err := loadDir[npc](filepath.Join(d, "npcs"), true, nil)
	if err != nil {
		return err
	}
	g.effects, err = loadDir[effect](filepath.Join(d, "effects"), false, func(e *effect) bool { return e.Visible })
	if err != nil {
		return err
	}
	g.feats, err = loadDir[feat](filepath.Join(d, "systems", "feats"), false, nil)
	if err != nil {
		return err
	}
	g.abilities, err = loadDir[ability](filepath.Join(d, "systems", "abilities"), true, nil)
	if err != nil {
		return err
	}
	pois, err := loadDir[poi](filepath.Join(d, "locations", "poi-draft"), false, nil)
	if err != nil {
		return err
	}
	encounters, err := loadDir[encounter](filepath.Join(d, "systems", "encounters-draft"), false, nil)
	if err != nil {
		return err
	}
	quests, err := loadDir[quest](filepath.Join(d, "quests-drafts"), true, func(q *quest) bool { return q.ID != "" })
	if err != nil {
		return err
	}
	if g.chars, err = loadCharacters(d); err != nil {
		return err
	}
	g.pois, g.encounters, g.quests = map[string]*poi{}, map[string]*encounter{}, map[string]*quest{}
	for _, p := range pois {
		g.pois[p.ID] = p
	}
	for _, e := range encounters {
		g.encounters[e.ID] = e
	}
	for _, q := range quests {
		g.quests[q.ID] = q
	}

	g.items = map[string]*item{}
	for _, it := range items {
		g.items[it.ID] = it
	}
	g.monsters = map[string]*monster{}
	for _, m := range monsters {
		g.monsters[m.ID] = m
	}
	g.spells = map[string]*spell{}
	for _, s := range spells {
		g.spells[s.ID] = s
	}
	g.cities = map[string]*city{}
	for _, c := range cities {
		g.cities[c.ID] = c
	}
	g.envs = map[string]*environment{}
	for _, e := range envs {
		g.envs[e.ID] = e
	}
	g.npcs = map[string]*npc{}
	for _, n := range npcs {
		g.npcs[n.ID] = n
	}
	g.loadExtras()
	return nil
}

func (g *gen) index() {
	g.droppedBy, g.soldBy, g.inPacks = map[string][]string{}, map[string][]string{}, map[string][]string{}
	g.setPieces, g.scrollsOf, g.usedBy = map[string][]string{}, map[string][]string{}, map[string][]string{}
	g.npcsAt, g.district = map[string][]string{}, map[string]string{}

	for _, m := range sortedKeys(g.monsters) {
		for _, id := range g.monsters[m].lootItems() {
			addOnce(g.droppedBy, id, m)
		}
	}
	for _, n := range sortedKeys(g.npcs) {
		np := g.npcs[n]
		addOnce(g.npcsAt, np.PrimaryHome, n)
		if np.Shop != nil {
			for _, s := range np.Shop.Inventory {
				addOnce(g.soldBy, s.ItemID, n)
			}
		}
	}
	for _, id := range sortedKeys(g.items) {
		it := g.items[id]
		for _, c := range it.contents() {
			addOnce(g.inPacks, c.id, id)
		}
		if it.Set != "" {
			addOnce(g.setPieces, it.Set, id)
		}
		if it.SpellID != "" {
			addOnce(g.scrollsOf, it.SpellID, id)
		}
	}
	for _, id := range sortedKeys(g.spells) {
		if mc := g.spells[id].Material; mc != nil {
			for _, r := range mc.Required {
				addOnce(g.usedBy, r.Component, id)
			}
		}
	}
	for _, c := range g.cities {
		for _, dist := range c.Districts {
			g.district[dist.ID] = c.ID
		}
	}

	g.foundIn, g.metIn, g.poisIn, g.questsAt = map[string][]string{}, map[string][]string{}, map[string][]string{}, map[string][]string{}
	place := func(where string, nodes map[string]node) {
		s := g.summarize(nodes)
		for _, id := range s.loot {
			addOnce(g.foundIn, id, where)
		}
		for _, n := range nodes {
			if n.MonsterID != "" {
				addOnce(g.metIn, n.MonsterID, where)
			}
		}
	}
	for _, id := range sortedKeys(g.pois) {
		p := g.pois[id]
		addOnce(g.poisIn, p.Environment, id)
		place(g.poiLink(id), p.Nodes)
	}
	for _, id := range sortedKeys(g.encounters) {
		place(link(g.encounters[id].Name, "Encounters"), g.encounters[id].Nodes)
	}
	for _, id := range sortedKeys(g.quests) {
		q := g.quests[id]
		ql := g.questLink(id)
		if g.pois[q.Start.Target] != nil {
			addOnce(g.questsAt, q.Start.Target, id)
		}
		for _, st := range q.Stages {
			for _, o := range st.Objectives {
				if g.pois[o.Target] != nil {
					addOnce(g.questsAt, o.Target, id)
				}
				if o.Type == "slay" && g.monsters[o.Target] != nil {
					addOnce(g.metIn, o.Target, ql)
				}
			}
			if st.Rewards != nil {
				for _, it := range st.Rewards.Items {
					addOnce(g.foundIn, it.ID, ql)
				}
			}
		}
	}
	g.indexExtras()
}

// ── writing ──────────────────────────────────────────────────────────────────

// page writes a generated page at rel (slash path, no extension).
func (g *gen) page(rel, title string, body string) error {
	var b strings.Builder
	b.WriteString(Marker + "\n")
	if title != "" {
		b.WriteString("# " + title + "\n\n")
	}
	if crumbs := breadcrumbs(rel); crumbs != "" {
		b.WriteString(crumbs + "\n\n")
	}
	b.WriteString(strings.TrimRight(body, "\n") + "\n" + dataNote)
	return g.writeFile(rel+".md", b.String())
}

func (g *gen) writeFile(rel, content string) error {
	path := filepath.Join(g.opt.OutDir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	g.written[rel] = true
	g.res.Pages++
	return os.WriteFile(path, []byte(content), 0o644)
}

// image copies a /res/img/... asset into media/ and returns an <img> for it, or
// "" when the art doesn't exist yet.
func (g *gen) image(webPath, alt string, width int) string {
	rel := strings.TrimPrefix(webPath, "/res/img/")
	if rel == webPath || rel == "" {
		return ""
	}
	src := filepath.Join(g.opt.ImageDir, filepath.FromSlash(rel))
	dst := filepath.Join(g.opt.OutDir, "media", filepath.FromSlash(rel))
	if _, err := os.Stat(dst); err != nil {
		if err := copyFile(src, dst); err != nil {
			return ""
		}
		g.res.Images++
	}
	// Raw <img>: Gollum 6 drops the width option of its [[image]] tag.
	// Gollum prefixes its own [[links]] with the base path, but not raw HTML.
	// The ?v= fingerprint changes when the art does, so a redrawn sprite isn't
	// hidden behind the old one in browser and CDN caches (media is cached for hours).
	return fmt.Sprintf(`<img src="%s/media/%s?v=%s" alt="%s" width="%d">`,
		strings.TrimRight(g.opt.BasePath, "/"), rel, fileFingerprint(dst), html.EscapeString(alt), width)
}

// fileFingerprint is a short content hash for cache-busting image URLs.
func fileFingerprint(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		return "0"
	}
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:4])
}

func copyFile(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	out, err := os.Create(dst)
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, in); err != nil {
		out.Close()
		return err
	}
	return out.Close()
}

// removeStale deletes generated pages this run didn't write (their data is gone).
func (g *gen) removeStale() error {
	return filepath.WalkDir(g.opt.OutDir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if d.Name() == ".git" || d.Name() == "media" {
				return filepath.SkipDir
			}
			return nil
		}
		if filepath.Ext(path) != ".md" {
			return nil
		}
		rel, _ := filepath.Rel(g.opt.OutDir, path)
		if g.written[filepath.ToSlash(rel)] || !isGenerated(path) {
			return nil
		}
		g.res.Removed++
		return os.Remove(path)
	})
}

func isGenerated(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	buf := make([]byte, len(Marker))
	n, _ := io.ReadFull(f, buf)
	return string(buf[:n]) == Marker
}

// codexURL is where game data is edited.
const codexURL = "https://codex.pubkey.quest"

// dataNote closes every generated page: where its content comes from.
const dataNote = "\n---\n_Generated from the game's data. To change it, edit the data in [Codex](" + codexURL + ")._\n"

// writeHome writes the front page and the sidebar.
func (g *gen) writeHome() error {
	type section struct{ name, path, about string }
	groups := []struct {
		title    string
		sections []section
	}{
		{"How the game works", []section{
			{"Combat", "Rules/Combat", "turns, dice, advantage, terrain, traps"},
			{"Hunger, Fatigue & Carrying", "Rules/Survival", "food, rest, encumbrance"},
			{"Day & Night", "Rules/Day-and-Night", "the clock, darkness, night monsters"},
			{"Learning Spells", "Rules/Learning-Spells", "what each class learns, and when"},
			{"Scribing Scrolls", "Rules/Scribing", "stations, costs, Commit to memory"},
			{"Homeward Stones & Waystones", "Rules/Teleportation", "getting around fast"},
			{"Rules", "Rules", "conditions & effects, feats, class abilities"},
		}},
		{"The world", []section{
			{"World Map", "Map", "every town and road"},
			{"Locations", "Locations", fmt.Sprintf("%d towns, %d regions, %d places of interest", len(g.cities), len(g.envs), len(g.pois))},
			{"NPCs", "NPCs", fmt.Sprintf("%d people: schedules, shops and services", len(g.npcs))},
			{"Quests", "Quests", fmt.Sprintf("%d quests", len(g.quests))},
			{"Encounters", "Encounters", "events on the road and in town"},
		}},
		{"Reference", []section{
			{"Items", "Items", fmt.Sprintf("%d weapons, armor, gear, potions, scrolls and components", len(g.items))},
			{"Monsters", "Monsters", fmt.Sprintf("%d creatures: stats, habitats, loot", len(g.monsters))},
			{"Spells", "Spells", fmt.Sprintf("%d spells by level and class", len(g.spells))},
			{"Characters", "Characters", "races, classes, skills, leveling"},
		}},
	}
	var b, side strings.Builder
	b.WriteString("Reference for [Pubkey Quest](/), built from the game's own data so it matches the game.\n\n")
	side.WriteString("**[[Home|/Home]]**\n\n")
	for _, grp := range groups {
		b.WriteString("## " + grp.title + "\n\n")
		side.WriteString("**" + grp.title + "**\n\n")
		for _, s := range grp.sections {
			b.WriteString("- " + link(s.name, s.path) + " — " + s.about + "\n")
			side.WriteString("- " + link(s.name, s.path) + "\n")
		}
		b.WriteString("\n")
		side.WriteString("\n")
	}
	b.WriteString("## About this wiki\n\n" +
		"These pages are rebuilt from the game's data with every update. To change something here, " +
		"edit the game data in [Codex](" + codexURL + ").\n\n" +
		"Community pages (guides, strategy, lore) will be editable here in a future update.\n")
	if err := g.writeFile("Home.md", Marker+"\n# Pubkey Quest Wiki\n\n"+b.String()); err != nil {
		return err
	}
	return g.writeFile("_Sidebar.md", Marker+"\n"+side.String())
}

// The theme is generated so the wiki tracks the game's look; gollum loads it with
// --css and --js.
var (
	//go:embed theme.css
	themeCSS string
	//go:embed theme.js
	themeJS string
)

func (g *gen) writeTheme() error {
	js := strings.ReplaceAll(themeJS, "__WIKI_BASE__", strings.TrimRight(g.opt.BasePath, "/")+"/")
	for name, content := range map[string]string{"custom.css": themeCSS, "custom.js": js} {
		path := filepath.Join(g.opt.OutDir, name)
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// ── markdown helpers ─────────────────────────────────────────────────────────

func link(label, path string) string { return "[[" + label + "|/" + path + "]]" }

// cell escapes text for a table cell (wiki links are extracted before rendering,
// so their pipes are safe).
func cell(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	return strings.ReplaceAll(s, "|", "\\|")
}

func table(b *strings.Builder, head []string, rows [][]string) {
	if len(rows) == 0 {
		return
	}
	b.WriteString("| " + strings.Join(head, " | ") + " |\n|")
	for range head {
		b.WriteString("---|")
	}
	b.WriteString("\n")
	for _, r := range rows {
		b.WriteString("| " + strings.Join(r, " | ") + " |\n")
	}
	b.WriteString("\n")
}

// facts renders a headerless key/value infobox, skipping empty values. It's an HTML
// table (markdown tables need a header row); wiki links inside still resolve.
func facts(b *strings.Builder, kv ...string) {
	var rows []string
	for i := 0; i+1 < len(kv); i += 2 {
		if kv[i+1] != "" {
			rows = append(rows, "<tr><th>"+kv[i]+"</th><td>"+kv[i+1]+"</td></tr>")
		}
	}
	if len(rows) > 0 {
		b.WriteString("<table>\n" + strings.Join(rows, "\n") + "\n</table>\n\n")
	}
}

func bullets(b *strings.Builder, heading string, lines []string) {
	if len(lines) == 0 {
		return
	}
	if heading != "" {
		b.WriteString("## " + heading + "\n\n")
	}
	for _, l := range lines {
		b.WriteString("- " + l + "\n")
	}
	b.WriteString("\n")
}

func titleCase(s string) string {
	s = strings.NewReplacer("_", " ", "-", " ").Replace(s)
	words := strings.Fields(s)
	for i, w := range words {
		words[i] = strings.ToUpper(w[:1]) + w[1:]
	}
	return strings.Join(words, " ")
}

func num(v any) string {
	switch x := v.(type) {
	case nil:
		return ""
	case float64:
		return fmt.Sprintf("%g", x)
	case string:
		return x
	default:
		return fmt.Sprint(x)
	}
}

func clock(min int) string { return fmt.Sprintf("%02d:%02d", (min/60)%24, min%60) }

func duration(min int) string {
	switch {
	case min <= 0:
		return ""
	case min%1440 == 0:
		return plural(min/1440, "day")
	case min%60 == 0:
		return plural(min/60, "hour")
	case min > 60:
		return plural(min/60, "hour") + " " + plural(min%60, "minute")
	}
	return plural(min, "minute")
}

func plural(n int, unit string) string {
	if n == 1 {
		return "1 " + unit
	}
	return fmt.Sprintf("%d %ss", n, unit)
}

func gold(n int) string { return fmt.Sprintf("%d gold", n) }

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func addOnce(m map[string][]string, key, val string) {
	if key == "" {
		return
	}
	for _, v := range m[key] {
		if v == val {
			return
		}
	}
	m[key] = append(m[key], val)
}

// publicNotes drops design/engine notes that aren't meant for players.
func publicNotes(notes []string) []string {
	var out []string
	for _, n := range notes {
		l := strings.ToLower(n)
		if strings.Contains(l, "engine") || strings.Contains(l, "not yet implemented") ||
			strings.Contains(l, "[~]") || strings.Contains(l, "todo") || strings.Contains(l, "modeled by") {
			continue
		}
		out = append(out, n)
	}
	return out
}

// breadcrumbs links a page back up its path: "Home › Items" under an item's title.
func breadcrumbs(rel string) string {
	parts := strings.Split(rel, "/")
	if len(parts) < 2 {
		return ""
	}
	crumbs := []string{link("Home", "Home")}
	for i := 0; i < len(parts)-1; i++ {
		crumbs = append(crumbs, link(strings.ReplaceAll(parts[i], "-", " "), strings.Join(parts[:i+1], "/")))
	}
	return "<sub>" + strings.Join(crumbs, " › ") + "</sub>"
}
