// ── markdown helpers ─────────────────────────────────────────────────────────

func link(label, path string) string { return "[[" + label + "|/" + path + "]]" }

// cell escapes text for a table cell (wiki links are extracted before rendering,
// so their pipes are safe).
func cell(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	return strings.ReplaceAll(s, "|", "\\|")
}

func table(b *strings.Builder, head []string, rows [][]string) {
	if len(rows) == 0 {
		return
	}
	b.WriteString("| " + strings.Join(head, " | ") + " |\n|")
	for range head {
		b.WriteString("---|")
	}
	b.WriteString("\n")
	for _, r := range rows {
		b.WriteString("| " + strings.Join(r, " | ") + " |\n")
	}
	b.WriteString("\n")
}

// facts renders a headerless key/value infobox, skipping empty values. It's an HTML
// table (markdown tables need a header row); wiki links inside still resolve.
func facts(b *strings.Builder, kv ...string) {
	var rows []string
	for i := 0; i+1 < len(kv); i += 2 {
		if kv[i+1] != "" {
			rows = append(rows, "<tr><th>"+kv[i]+"</th><td>"+kv[i+1]+"</td></tr>")
		}
	}
	if len(rows) > 0 {
		b.WriteString("<table>\n" + strings.Join(rows, "\n") + "\n</table>\n\n")
	}
}

func bullets(b *strings.Builder, heading string, lines []string) {
	if len(lines) == 0 {
		return
	}
	if heading != "" {
		b.WriteString("## " + heading + "\n\n")
	}
	for _, l := range lines {
		b.WriteString("- " + l + "\n")
	}
	b.WriteString("\n")
}

func titleCase(s string) string {
	s = strings.NewReplacer("_", " ", "-", " ").Replace(s)
	words := strings.Fields(s)
	for i, w := range words {
		words[i] = strings.ToUpper(w[:1]) + w[1:]
	}
	return strings.Join(words, " ")
}

func num(v any) string {
	switch x := v.(type) {
	case nil:
		return ""
	case float64:
		return fmt.Sprintf("%g", x)
	case string:
		return x
	default:
		return fmt.Sprint(x)
	}
}

func clock(min int) string { return fmt.Sprintf("%02d:%02d", (min/60)%24, min%60) }

func duration(min int) string {
	switch {
	case min <= 0:
		return ""
	case min%1440 == 0:
		return plural(min/1440, "day")
	case min%60 == 0:
		return plural(min/60, "hour")
	case min > 60:
		return plural(min/60, "hour") + " " + plural(min%60, "minute")
	}
	return plural(min, "minute")
}

func plural(n int, unit string) string {
	if n == 1 {
		return "1 " + unit
	}
	return fmt.Sprintf("%d %ss", n, unit)
}

func gold(n int) string { return fmt.Sprintf("%d gold", n) }

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func addOnce(m map[string][]string, key, val string) {
	if key == "" {
		return
	}
	for _, v := range m[key] {
		if v == val {
			return
		}
	}
	m[key] = append(m[key], val)
}

// publicNotes drops design/engine notes that aren't meant for players.
func publicNotes(notes []string) []string {
	var out []string
	for _, n := range notes {
		l := strings.ToLower(n)
		if strings.Contains(l, "engine") || strings.Contains(l, "not yet implemented") ||
			strings.Contains(l, "[~]") || strings.Contains(l, "todo") || strings.Contains(l, "modeled by") {
			continue
		}
		out = append(out, n)
	}
	return out
}
