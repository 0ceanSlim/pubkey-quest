// Package wiki generates Gollum wiki pages from game-data/ (codex --wiki <dir>).
//
// The output directory is a working copy of the wiki's git repo. The generator owns
// every page whose first line is the generated marker, plus the media/ folder: it
// rewrites those on each run and deletes the ones whose source data is gone.
// Anything else in the repo — hand-written pages, Home, the sidebar once it exists —
// is never touched, so generated reference pages and community pages live side by
// side. Pages are named by id (stable links when a name changes); Gollum runs with
// --h1-title so the first H1 is the displayed title.
package wiki

import (
	_ "embed"
	"encoding/json"
	"fmt"
	"html"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Marker is the first line of every generated page.
const Marker = "<!-- generated by codex --wiki: edits to this page are overwritten -->"

// Options says where to read game data and art, and where the wiki lives.
type Options struct {
	DataDir  string // game-data
	ImageDir string // www/res/img
	OutDir   string // wiki repo working copy
	BasePath string // where Gollum is served (gollum --base-path), e.g. "/wiki"
}

// Result counts what a run did.
type Result struct {
	Pages   int
	Images  int
	Removed int
	Seeded  []string
}

// Generate writes the generated pages into opt.OutDir.
func Generate(opt Options) (*Result, error) {
	if err := os.MkdirAll(opt.OutDir, 0o755); err != nil {
		return nil, err
	}
	g := &gen{opt: opt, written: map[string]bool{}, res: &Result{}}
	if err := g.load(); err != nil {
		return nil, err
	}
	g.index()

	// media/ is wholly generated — start it clean so removed art disappears.
	if err := os.RemoveAll(filepath.Join(opt.OutDir, "media")); err != nil {
		return nil, err
	}

	steps := []func() error{
		g.writeItems, g.writeMonsters, g.writeSpells, g.writeLocations,
		g.writeNPCs, g.writeRules, g.writeFooters, g.writeTheme, g.seed,
	}
	for _, step := range steps {
		if err := step(); err != nil {
			return nil, err
		}
	}
	if err := g.removeStale(); err != nil {
		return nil, err
	}
	return g.res, nil
}

type gen struct {
	opt     Options
	res     *Result
	written map[string]bool // slash paths written this run

	items     map[string]*item
	monsters  map[string]*monster
	spells    map[string]*spell
	cities    map[string]*city
	envs      map[string]*environment
	npcs      map[string]*npc
	effects   []*effect
	feats     []*feat
	abilities []*ability

	// reverse indexes
	droppedBy map[string][]string // item id → monster ids
	soldBy    map[string][]string // item id → npc ids
	inPacks   map[string][]string // item id → pack ids
	setPieces map[string][]string // set item id → piece ids
	scrollsOf map[string][]string // spell id → scroll item ids
	usedBy    map[string][]string // component item id → spell ids
	npcsAt    map[string][]string // home id → npc ids
	district  map[string]string   // district id → city id
}

// ── loading ──────────────────────────────────────────────────────────────────

func loadDir[T any](dir string, recursive bool, keep func(*T) bool) ([]*T, error) {
	var out []*T
	err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if path != dir && !recursive {
				return filepath.SkipDir
			}
			return nil
		}
		if filepath.Ext(path) != ".json" {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		v := new(T)
		if err := json.Unmarshal(data, v); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		if fa, ok := any(v).(interface{ setFile(string) }); ok {
			fa.setFile(path)
		}
		if keep == nil || keep(v) {
			out = append(out, v)
		}
		return nil
	})
	return out, err
}

func (g *gen) load() error {
	d := g.opt.DataDir
	items, err := loadDir[item](filepath.Join(d, "items"), false, nil)
	if err != nil {
		return err
	}
	monsters, err := loadDir[monster](filepath.Join(d, "monsters"), false, nil) // skips monsters/wip
	if err != nil {
		return err
	}
	spells, err := loadDir[spell](filepath.Join(d, "magic", "spells"), false, nil)
	if err != nil {
		return err
	}
	cities, err := loadDir[city](filepath.Join(d, "locations", "cities"), false, nil)
	if err != nil {
		return err
	}
	envs, err := loadDir[environment](filepath.Join(d, "locations", "environments"), false, nil)
	if err != nil {
		return err
	}
	npcs, err := loadDir[npc](filepath.Join(d, "npcs"), true, nil)
	if err != nil {
		return err
	}
	g.effects, err = loadDir[effect](filepath.Join(d, "effects"), false, func(e *effect) bool { return e.Visible })
	if err != nil {
		return err
	}
	g.feats, err = loadDir[feat](filepath.Join(d, "systems", "feats"), false, nil)
	if err != nil {
		return err
	}
	g.abilities, err = loadDir[ability](filepath.Join(d, "systems", "abilities"), true, nil)
	if err != nil {
		return err
	}

	g.items = map[string]*item{}
	for _, it := range items {
		g.items[it.ID] = it
	}
	g.monsters = map[string]*monster{}
	for _, m := range monsters {
		g.monsters[m.ID] = m
	}
	g.spells = map[string]*spell{}
	for _, s := range spells {
		g.spells[s.ID] = s
	}
	g.cities = map[string]*city{}
	for _, c := range cities {
		g.cities[c.ID] = c
	}
	g.envs = map[string]*environment{}
	for _, e := range envs {
		g.envs[e.ID] = e
	}
	g.npcs = map[string]*npc{}
	for _, n := range npcs {
		g.npcs[n.ID] = n
	}
	return nil
}

func (g *gen) index() {
	g.droppedBy, g.soldBy, g.inPacks = map[string][]string{}, map[string][]string{}, map[string][]string{}
	g.setPieces, g.scrollsOf, g.usedBy = map[string][]string{}, map[string][]string{}, map[string][]string{}
	g.npcsAt, g.district = map[string][]string{}, map[string]string{}

	for _, m := range sortedKeys(g.monsters) {
		for _, id := range g.monsters[m].lootItems() {
			addOnce(g.droppedBy, id, m)
		}
	}
	for _, n := range sortedKeys(g.npcs) {
		np := g.npcs[n]
		addOnce(g.npcsAt, np.PrimaryHome, n)
		if np.Shop != nil {
			for _, s := range np.Shop.Inventory {
				addOnce(g.soldBy, s.ItemID, n)
			}
		}
	}
	for _, id := range sortedKeys(g.items) {
		it := g.items[id]
		for _, c := range it.contents() {
			addOnce(g.inPacks, c.id, id)
		}
		if it.Set != "" {
			addOnce(g.setPieces, it.Set, id)
		}
		if it.SpellID != "" {
			addOnce(g.scrollsOf, it.SpellID, id)
		}
	}
	for _, id := range sortedKeys(g.spells) {
		if mc := g.spells[id].Material; mc != nil {
			for _, r := range mc.Required {
				addOnce(g.usedBy, r.Component, id)
			}
		}
	}
	for _, c := range g.cities {
		for _, dist := range c.Districts {
			g.district[dist.ID] = c.ID
		}
	}
}

// ── writing ──────────────────────────────────────────────────────────────────

// page writes a generated page at rel (slash path, no extension).
func (g *gen) page(rel, title string, body string) error {
	var b strings.Builder
	b.WriteString(Marker + "\n")
	if title != "" {
		b.WriteString("# " + title + "\n\n")
	}
	b.WriteString(strings.TrimRight(body, "\n") + "\n")
	return g.writeFile(rel+".md", b.String())
}

func (g *gen) writeFile(rel, content string) error {
	path := filepath.Join(g.opt.OutDir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	g.written[rel] = true
	g.res.Pages++
	return os.WriteFile(path, []byte(content), 0o644)
}

// image copies a /res/img/... asset into media/ and returns an <img> for it, or
// "" when the art doesn't exist yet.
func (g *gen) image(webPath, alt string, width int) string {
	rel := strings.TrimPrefix(webPath, "/res/img/")
	if rel == webPath || rel == "" {
		return ""
	}
	src := filepath.Join(g.opt.ImageDir, filepath.FromSlash(rel))
	dst := filepath.Join(g.opt.OutDir, "media", filepath.FromSlash(rel))
	if _, err := os.Stat(dst); err != nil {
		if err := copyFile(src, dst); err != nil {
			return ""
		}
		g.res.Images++
	}
	// Raw <img>: Gollum 6 drops the width option of its [[image]] tag.
	// Gollum prefixes its own [[links]] with the base path, but not raw HTML.
	return fmt.Sprintf(`<img src="%s/media/%s" alt="%s" width="%d">`,
		strings.TrimRight(g.opt.BasePath, "/"), rel, html.EscapeString(alt), width)
}

func copyFile(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	out, err := os.Create(dst)
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, in); err != nil {
		out.Close()
		return err
	}
	return out.Close()
}

// removeStale deletes generated pages this run didn't write (their data is gone).
func (g *gen) removeStale() error {
	return filepath.WalkDir(g.opt.OutDir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if d.Name() == ".git" || d.Name() == "media" {
				return filepath.SkipDir
			}
			return nil
		}
		if filepath.Ext(path) != ".md" {
			return nil
		}
		rel, _ := filepath.Rel(g.opt.OutDir, path)
		if g.written[filepath.ToSlash(rel)] || !isGenerated(path) {
			return nil
		}
		g.res.Removed++
		return os.Remove(path)
	})
}

func isGenerated(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	buf := make([]byte, len(Marker))
	n, _ := io.ReadFull(f, buf)
	return string(buf[:n]) == Marker
}

// writeFooters gives every generated folder a footer saying where edits belong.
func (g *gen) writeFooters() error {
	footer := Marker + "\n_This page is generated from the game's data and rebuilt on every update — " +
		"edits made here are overwritten. Tips, strategy and lore belong on the community pages " +
		"(see [[Home|/Home]])._\n"
	for _, dir := range []string{"Items", "Monsters", "Spells", "Locations", "NPCs", "Rules"} {
		if err := g.writeFile(dir+"/_Footer.md", footer); err != nil {
			return err
		}
	}
	return nil
}

// The theme is generated (not seeded) so the wiki tracks the game's look; gollum
// loads it with --css and --js.
var (
	//go:embed theme.css
	themeCSS string
	//go:embed theme.js
	themeJS string
)

func (g *gen) writeTheme() error {
	for name, content := range map[string]string{"custom.css": themeCSS, "custom.js": themeJS} {
		path := filepath.Join(g.opt.OutDir, name)
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// seed writes the hand-editable starter pages only if they don't exist yet.
func (g *gen) seed() error {
	for name, content := range seedPages {
		path := filepath.Join(g.opt.OutDir, name)
		if _, err := os.Stat(path); err == nil {
			continue
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return err
		}
		g.res.Seeded = append(g.res.Seeded, name)
	}
	sort.Strings(g.res.Seeded)
	return nil
}

